from typing import List, Dict, Any, Optional
from pydantic import BaseModel, Field


class DateRange(BaseModel):
    start: Optional[str] = Field(None, description="Earliest transaction date (YYYY-MM-DD)")
    end: Optional[str] = Field(None, description="Latest transaction date (YYYY-MM-DD)")


class DatasetMeta(BaseModel):
    filename: str = Field(..., description="Name of the analyzed file")
    row_count: int = Field(..., ge=0, description="Total number of records")
    column_count: int = Field(..., ge=0, description="Total number of columns")
    date_range: Optional[DateRange] = Field(None, description="Start and end dates of the dataset")


class ColumnProfile(BaseModel):
    name: str = Field(..., description="Column header name")
    inferred_type: str = Field(..., description="Inferred analytical data type")
    null_count: int = Field(..., ge=0, description="Number of missing or NaN values")
    null_percentage: float = Field(..., ge=0.0, le=100.0, description="Percentage of missing values")


class DataQualityReport(BaseModel):
    completeness_score: float = Field(..., ge=0.0, le=100.0, description="Overall non-null data completeness percentage")
    duplicate_rows: int = Field(..., ge=0, description="Count of duplicate rows")
    columns_profile: List[ColumnProfile] = Field(..., description="Detailed profile per column")
    validation_status: str = Field("valid", description="Schema validation status: 'valid' or 'warning'")
    validation_notes: List[str] = Field(default_factory=list, description="Any schema caveats or warnings")


class CoreMetrics(BaseModel):
    total_revenue: float = Field(..., description="Total gross net revenue ($)")
    total_orders: int = Field(..., ge=0, description="Count of distinct orders")
    average_order_value: float = Field(..., description="Average revenue per order ($)")
    total_units_sold: int = Field(..., ge=0, description="Total volume of units sold")
    average_discount: float = Field(..., ge=0.0, le=1.0, description="Average discount rate applied")


class MonthlyTrend(BaseModel):
    month: str = Field(..., description="Year and month identifier (YYYY-MM)")
    revenue: float = Field(..., description="Total revenue generated in this month")
    order_count: int = Field(..., ge=0, description="Number of unique orders in this month")
    mom_growth_pct: Optional[float] = Field(None, description="Month-over-month revenue growth rate percentage")


class TopProduct(BaseModel):
    product_id: str = Field(..., description="Unique product SKU")
    product_name: str = Field(..., description="Product label")
    category: str = Field(..., description="Product category")
    revenue: float = Field(..., description="Total revenue generated by product")
    units_sold: int = Field(..., ge=0, description="Total units sold")
    share_of_total_pct: float = Field(..., ge=0.0, le=100.0, description="Percentage share of total revenue")


class RegionalPerformance(BaseModel):
    region: str = Field(..., description="Territory or region label")
    revenue: float = Field(..., description="Total revenue in region")
    order_count: int = Field(..., ge=0, description="Unique order count in region")
    aov: float = Field(..., description="Average order value in region ($)")
    share_of_total_pct: float = Field(..., ge=0.0, le=100.0, description="Percentage share of total revenue")


class AutomatedInsight(BaseModel):
    id: str = Field(..., description="Unique identifier for insight")
    category: str = Field(..., description="Insight category: 'growth', 'concentration', 'outlier', 'performance'")
    title: str = Field(..., description="Concise analytical finding title")
    description: str = Field(..., description="Detailed, fact-checked finding explanation")
    metric_reference: str = Field(..., description="Associated metric or computed value")


class AnalysisResponse(BaseModel):
    dataset_id: str = Field("default", description="Unique dataset identifier for session grounding")
    dataset_meta: DatasetMeta
    data_quality: DataQualityReport
    metrics: CoreMetrics
    monthly_trends: List[MonthlyTrend]
    top_products: List[TopProduct]
    regional_performance: List[RegionalPerformance]
    top5_revenue_concentration_pct: float = Field(..., ge=0.0, le=100.0, description="Share of revenue from top 5 products")
    automated_insights: List[AutomatedInsight]
    preview_rows: List[Dict[str, Any]]


class AskQuestionRequest(BaseModel):
    question: str = Field(..., min_length=1, max_length=500, description="The user's analytical query")
    dataset_id: Optional[str] = Field(None, description="Identifier of the active dataset to query against")


class AskQuestionResponse(BaseModel):
    answer: str = Field(..., description="Natural language analytical response grounded strictly in calculated metrics")
    observed_facts: List[str] = Field(default_factory=list, description="Key verified metrics and observations directly referenced")
    recommendations: List[str] = Field(default_factory=list, description="Recommended investigative follow-ups or analytical caveats")
    is_grounded: bool = Field(True, description="Whether the answer is grounded in verified computational context")
    model_used: Optional[str] = Field(None, description="Name of the Gemini model used")
    ai_configured: bool = Field(True, description="Whether the Gemini AI backend is configured and functional")


class AiStatusResponse(BaseModel):
    configured: bool = Field(..., description="Whether GEMINI_API_KEY is present")
    model: str = Field(..., description="Configured Gemini model")
